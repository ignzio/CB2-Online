"""Turns assets/fonts/crash-a-like.ttf into src/crash_font.inc (a C array), so the lobby carries its font inside the executable.
Run:  python tools/embed_font.py
The font is "Crash-a-Like" by Aryel Filipe (dafont.com, listed as 100% free)."""
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = open(os.path.join(root, "assets", "fonts", "crash-a-like.ttf"), "rb").read()
lines = ["// Generated by tools/embed_font.py from assets/fonts/crash-a-like.ttf (Crash-a-Like by Aryel Filipe, dafont.com, 100% free).",
         "static const unsigned char kCrashFont[%d] = {" % len(data)]
for i in range(0, len(data), 24):
    lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
lines.append("};")
open(os.path.join(root, "src", "crash_font.inc"), "w", newline="\n").write("\n".join(lines) + "\n")
print("wrote src/crash_font.inc,", len(data), "bytes")
