"""Generates src/gool_fields.inc (process field names) from CrashEdit's ObjectFields enum.

Usage: python gen_gool_fields.py <GOOLInterpreter.cs> <out.inc>
The names are community documentation of the game's process layout; only the identifiers are used.
"""
import re
import sys

text = open(sys.argv[1], encoding='utf-8').read()
body = re.search(r'enum ObjectFields\s*\{(.*?)\};', text, re.S).group(1)
names = {}
cur = 0
for token in body.split(','):
    token = token.strip()
    if not token:
        continue
    m = re.match(r'(\w+)\s*=\s*(\d+)$', token)
    if m:
        cur = int(m.group(2))
        names[cur] = m.group(1)
    else:
        names[cur] = token
    cur += 1

expected = list(range(max(names) + 1))
if sorted(names) != expected:
    sys.exit('gap in field numbering')
lines = ['// Generated by tools/gen_gool_fields.py from the community ObjectFields table; do not edit by hand.']
lines += [f'"{names[i]}",' for i in expected]
open(sys.argv[2], 'w').write('\n'.join(lines) + '\n')
print(f'{len(names)} fields (0..{max(names)}): 8={names[8]}, 26={names[26]}, 64={names[64]}, {max(names)}={names[max(names)]}')
