"""Generates src/gool_ops.inc: per-opcode operand bit layouts for the Crash 2 GOOL instruction set.

Input: analysis/gool_ops.json (from extract_gool_ops.py). Layout strings are 24 operand bits, MSB first.
Brackets: [] value ref, {} destination ref, () process-field index, <> signed immediate.
"""
import json
import sys

DEFAULTS = {
    'GOOLInstruction.DefaultFormat': '[AAAAAAAAAAAA] [BBBBBBBBBBBB]',
    'GOOLInstruction.DefaultFormatLR': '[LLLLLLLLLLLL] [RRRRRRRRRRRR]',
    'GOOLInstruction.DefaultFormatDS': '[DDDDDDDDDDDD] [SSSSSSSSSSSS]',
    'GOOLInstruction.DefaultFormatDS2': '{DDDDDDDDDDDD} [SSSSSSSSSSSS]',
}
KIND = {'[': 'kRef', '{': 'kDest', '(': 'kField', '<': 'kSigned', None: 'kBits'}
CLOSE = {'[': ']', '{': '}', '(': ')', '<': '>'}


def resolve(fmt):
    if fmt in DEFAULTS:
        return DEFAULTS[fmt]
    if fmt.startswith('"') and fmt.endswith('.Reverse()'):
        return fmt[1:-len('".Reverse()')][::-1]
    return fmt.strip('"')


def parse(fmt):
    """Returns [(letter, kind, shift, width)] for named fields. Literal 0/1/- bits are not fields.

    Verified against the game's own branch and ADD/SUB handlers: the format strings are written LSB-first,
    i.e. the first character is bit 0 of the instruction word.
    """
    open_ch = None
    cells = []  # (char, kind) per bit, bit 0 first
    for c in fmt:
        if c in '[{(<':
            open_ch = c
        elif c in ']})>':
            open_ch = None
        elif c.isspace():
            continue
        else:
            cells.append((c, open_ch))
    if len(cells) != 24:
        raise ValueError(f'format has {len(cells)} bits: {fmt}')
    fields = []
    i = 0
    while i < 24:
        c, br = cells[i]
        if c in '01-':
            i += 1
            continue
        j = i
        while j < 24 and cells[j] == (c, br):
            j += 1
        fields.append((c, KIND[br], i, j - i))
        i = j
    return fields


ops = json.load(open(sys.argv[1]))
lines = ['// Generated by tools/gen_gool_ops.py from the opcode formats; do not edit by hand.']
for k in sorted(ops, key=int):
    op = ops[k]
    fmt = resolve(op['resolved'] or 'GOOLInstruction.DefaultFormat')
    fields = parse(fmt)
    body = ', '.join(f"{{'{c}', {kind}, {shift}, {width}}}" for c, kind, shift, width in fields)
    lines.append(f'{{{k}, "{op["name"]}", {{{body}}}}},')
open(sys.argv[2], 'w').write('\n'.join(lines) + '\n')
print(f'wrote {len(ops)} opcode layouts to {sys.argv[2]}')
